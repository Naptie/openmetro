/** The operator's official network payload (lines with their stops in order). */
export async function fetchOfficialAllLine(): Promise<OfficialAllLine> {
  return getJson<OfficialAllLine>(`${NC_API}/AllLine`, NC_REFERER);
}

/**
 * The operator's route quote for one OD pair.
 *
 * `startLine` / `endLine` must be lines the respective stations serve — see the
 * module comment. Returns `undefined` when the backend answers 500.
 */
export async function fetchOfficialRoute(
  name1: string,
  name2: string,
  startLine: string,
  endLine: string
): Promise<OfficialRoute | undefined> {
  return postForm<OfficialRoute>('/newselectByTowSiteName', {
    name1,
    name2,
    startLine,
    endLine
  });
}

/** The operator's per-station exits / bus interchange / landmarks. */
export async function fetchOfficialSiteInfo(name: string): Promise<OfficialSiteInfo[] | undefined> {
  const res = await postForm<OfficialSiteInfo[]>('/selectSiteInfo', { name });
  return Array.isArray(res) ? res : undefined;
}

/** AMap subway dataset (GCJ-02 native). */
export async function fetchAmapSubway(): Promise<AmapSubwayDoc> {
  return getJson<AmapSubwayDoc>(AMAP_SUBWAY, AMAP_REFERER);
}

export async function fetchNanchangSources(): Promise<NanchangSources> {
  if (process.env.OPENMETRO_REVERSE_PROXY) {
    console.log(`  via reverse proxy: ${process.env.OPENMETRO_REVERSE_PROXY}`);
  }

  console.log('  fetch official AllLine (network topology)');
  const official = await fetchOfficialAllLine();
  const lines = official.data ?? {};
  const lineIds = Object.keys(lines);
  const stopRows = lineIds.reduce((n, id) => n + (lines[id]?.length ?? 0), 0);
  console.log(
    `    ${lineIds.length} lines: ${lineIds
      .map((id) => `${id}号线×${lines[id]?.length ?? 0}`)
      .join(', ')} (${stopRows} line-stops)`
  );

  console.log('  fetch AMap subway 3601_drw_nanchang.json');
  const amap = await fetchAmapSubway();
  const amapStops = (amap.l ?? []).reduce((n, l) => n + (l.st?.length ?? 0), 0);
  console.log(`    ${(amap.l ?? []).length} lines, ${amapStops} stop rows`);

  if (lineIds.length < 4 || stopRows < 100) {
    throw new Error(
      `official AllLine looks truncated: ${lineIds.length} lines, ${stopRows} line-stops (expected 4 lines / 122 line-stops)`
    );
  }
  if ((amap.l ?? []).length === 0) {
    throw new Error('amap subway 3601 returned no lines');
  }

  return { official, amap };
}
