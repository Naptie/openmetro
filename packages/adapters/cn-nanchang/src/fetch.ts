/**
 * Official-source fetch for cn-nanchang.
 *
 * The operator website (www.ncmtr.com, 南昌轨道交通集团有限公司) is a
 * 中企动力 low-code CMS. Its own front-end bundle
 * (`/upload/js/16fd0c7a554c4d14a559d33e4c1956fc.js`) points at a plain JSON
 * backend that serves everything the site needs:
 *
 * - `GET  /guidao/apiNcdtFrontEnd/AllLine`
 *   → `{ list:[1,2,3,4], data:{ "1":[{siteName:"昌北机场站", …}], … } }`
 *   the operating lines with their stops in **official line order**.
 * - `POST /guidao/apiNcdtFrontEnd/newselectByTowSiteName`
 *   (multipart: `name1`, `name2`, `startLine`, `endLine`)
 *   → `{ routes, routesToList, NumberOfStations, TransferNumber, Price, time,
 *        gegeshijiantime }`
 *   the official route quote: the OD fare, the path split per line, the
 *   per-leg run time and the transfer count.
 * - `POST /guidao/apiNcdtFrontEnd/selectSiteInfo`
 *   (multipart: `name`)
 *   → `[{ entranceAndExitName, busStopName, busRoutes, biaozhiArr }, …]`
 *   the station's exits, its bus interchange and its landmarks.
 *
 * The backend needs no API key, no signature and no session. It is reachable
 * from any egress.
 *
 * ## The one trap: the line id must belong to the station
 *
 * `newselectByTowSiteName` answers **HTTP 500** when `startLine` / `endLine`
 * are not lines the named stations actually serve — it does not fall back to a
 * sensible route. Measured: 15 random OD pairs all sent `startLine=1,
 * endLine=1` produced 1 success and 14 failures; re-sent with each station's
 * real line the same sample produced 12/12 successes. Every caller therefore
 * has to expand the station → lines mapping (see `officialLinesFor` in
 * `./normalize.ts`) and try the combinations.
 *
 * Coordinates, the schematic pixel grid, per-line station codes, pinyin,
 * English names and line colours come from the public AMap subway dataset
 * (city code 3601). The operator publishes no coordinates at all.
 */
import { officialFetchHeaders, proxyUrl } from '@openmetro/core';

export const NC_SITE = 'https://www.ncmtr.com';
export const NC_REFERER = `${NC_SITE}/xlpj.html`;
export const NC_API = 'https://custproj00042-2.ceydz.com/guidao/apiNcdtFrontEnd';

export const AMAP_SUBWAY = 'https://webapi.amap.com/subway/data/3601_drw_nanchang.json';
export const AMAP_REFERER = 'https://www.amap.com/';

/** Official source identifiers used in `source_ids`. */
export const OFFICIAL_SOURCE = 'ncmtr-allline';
export const OFFICIAL_PLANNER_SOURCE = 'ncmtr-route-planner';
export const OFFICIAL_SITE_INFO_SOURCE = 'ncmtr-site-info';
export const AMAP_SOURCE = 'amap-subway-3601';

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function getText(url: string, referer: string, retries = 4): Promise<string> {
  let lastErr: unknown;
  for (let attempt = 0; attempt < retries; attempt++) {
    try {
      const res = await fetch(proxyUrl(url), {
        headers: officialFetchHeaders({ Referer: referer }),
        signal: AbortSignal.timeout(60_000)
      });
      if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
      return await res.text();
    } catch (err) {
      lastErr = err;
      const delay = 400 * 2 ** attempt;
      console.log(`  retry ${attempt + 1}/${retries} in ${delay}ms: ${err}`);
      await sleep(delay);
    }
  }
  throw lastErr instanceof Error ? lastErr : new Error(String(lastErr));
}

async function getJson<T>(url: string, referer: string, retries = 4): Promise<T> {
  return JSON.parse(await getText(url, referer, retries)) as T;
}

/**
 * POST a multipart form to the official backend.
 *
 * The operator's endpoints read `multipart/form-data` (the site's Vue
 * component builds a `FormData`), so the boundary must be generated by the
 * runtime — never set `Content-Type` by hand.
 *
 * Returns `undefined` on a non-2xx response: the planner answers **500** for a
 * line id the station does not serve, which is a routing condition rather than
 * an error the caller should retry blindly.
 */
async function postForm<T>(
  path: string,
  fields: Record<string, string>,
  retries = 3
): Promise<T | undefined> {
  let lastErr: unknown;
  for (let attempt = 0; attempt < retries; attempt++) {
    try {
      const form = new FormData();
      for (const [key, value] of Object.entries(fields)) form.append(key, value);
      const res = await fetch(proxyUrl(`${NC_API}${path}`), {
        method: 'POST',
        body: form,
        headers: officialFetchHeaders({ Referer: NC_REFERER }),
        signal: AbortSignal.timeout(60_000)
      });
      if (!res.ok) {
        // 500 = "no such route with these line ids" — a routing condition.
        if (res.status >= 500) return undefined;
        throw new Error(`POST ${path} -> ${res.status}`);
      }
      return (await res.json()) as T;
    } catch (err) {
      lastErr = err;
      const delay = 400 * 2 ** attempt;
      await sleep(delay);
    }
  }
  throw lastErr instanceof Error ? lastErr : new Error(String(lastErr));
}

