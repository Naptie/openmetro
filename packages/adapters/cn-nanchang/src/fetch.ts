/** One station entry of the operator's `AllLine` payload. */
export interface OfficialStation {
  id?: number;
  /** The line the entry belongs to (`1` … `4`). */
  metroLine?: number;
  /** The operator's internal site id. */
  siteLinkId?: number;
  /** The operator's station name, **with** the `站` suffix (`昌北机场站`). */
  siteName?: string;
}

/** The operator's `AllLine` payload: `data` is keyed by line id. */
export interface OfficialAllLine {
  list?: number[];
  data?: Record<string, OfficialStation[]>;
}

/** The operator's route quote for one OD pair. */
export interface OfficialRoute {
  /** One `{ stationName: lineId }` map per leg of the path. */
  routes?: Record<string, number>[];
  /** The path split per line: the ordered station names of each leg. */
  routesToList?: string[][];
  /** Number of stations on the path. */
  NumberOfStations?: number;
  /** Number of line changes on the path. */
  TransferNumber?: number;
  /** Official OD fare in yuan. */
  Price?: number;
  /** Total run time in minutes. */
  time?: number;
  /** Run time in minutes per leg of the path. */
  gegeshijiantime?: number[];
}

/** One exit / bus-interchange record of the operator's `selectSiteInfo`. */
export interface OfficialSiteInfo {
  entranceAndExitName?: string;
  busStopName?: string;
  busRoutes?: string;
  biaozhi?: string;
  biaozhiArr?: string;
  siteNameId?: number;
}

