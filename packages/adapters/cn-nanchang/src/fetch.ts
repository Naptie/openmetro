export interface AmapStation {
  n?: string;
  en?: string;
  /** CamelCase pinyin. */
  sp?: string;
  /** `lon,lat` in GCJ-02. */
  sl?: string;
  /** Schematic pixel pair `x y`. */
  p?: string;
  /** Station shape on the schematic map (`x y` or `x y|x y`). */
  rs?: string;
  /** Up/down schematic pixels, `x y;x y`. */
  udpx?: string;
  poiid?: string;
  /** Per-line station code. */
  si?: string;
  sid?: string;
  /** `1` for interchange stations. */
  t?: string | number;
  /** Lines the station belongs to, `|`-separated line ids. */
  r?: string;
  /** English name. */
  multilang?: { n?: { en?: string } };
}

export interface AmapLine {
  ln?: string;
  kn?: string;
  /** Line colour hex (no `#`). */
  cl?: string;
  lo?: string | number;
  li?: string;
  st?: AmapStation[];
  /** Schematic polyline, `x y` pairs. */
  c?: string[];
  /** Reverse schematic polyline. */
  f?: { c?: string[]; li?: string }[];
  multilang?: { ln?: Record<string, string>; kn?: Record<string, string> };
}

export interface AmapSubwayDoc {
  s?: string;
  i?: string;
  l?: AmapLine[];
}

export interface NanchangSources {
  /** The operator's `AllLine` payload. */
  official: OfficialAllLine;
  /** AMap subway dataset (GCJ-02 native). */
  amap: AmapSubwayDoc;
}

